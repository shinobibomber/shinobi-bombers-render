"""Derives website-design/website-screens.css (used inside the game page) from website/app.css.
Every selector is scoped under #sbwLayer and every @keyframes name is prefixed with sbw- so the website styles can
never affect the game's own UI. Re-run after editing website/app.css:  python3 website-src/make_game_css.py"""
import re,os
root=os.path.join(os.path.dirname(os.path.abspath(__file__)),'..')
css=open(os.path.join(root,'website','app.css'),encoding='utf-8').read()
css=re.sub(r'/\*.*?\*/','',css,flags=re.S)
names=set(re.findall(r'@keyframes\s+([\w-]+)',css))
for n in sorted(names,key=len,reverse=True):
    css=re.sub(r'(@keyframes\s+)'+re.escape(n)+r'\b',r'\1sbw-'+n,css)
    css=re.sub(r'(animation(?:-name)?\s*:[^;}]*?)(?<![\w-])'+re.escape(n)+r'(?![\w-])',lambda m:m.group(1)+'sbw-'+n,css)
    # second pass for multiple animations in one declaration
    css=re.sub(r'(animation(?:-name)?\s*:[^;}]*?,\s*)(?<![\w-])'+re.escape(n)+r'(?![\w-])',lambda m:m.group(1)+'sbw-'+n,css)
SKIP=('html','body',':root','#app','#toast','.md ','.md{','.md .','.scr','.stage','.dd','.srch','.cine','.res','.rc','.fph','.fdots','.fin','.rev','.rv','.rbtn','.mdetail','.fill','.dpanel','.hpov','.empty','.gcat','.arena','.abomb','.ablast','.apop','.aclear','.achip','.hbadge','.hlvl','.hdet','.htab','.chl','.chorig','.cmsg','.chttl','.chin','.chcnt','.dring','.dchip','.dskin','.dskr','.drp','.doff','.dtog','.dtl','.slotfill','.smtab','.ovstamp','.owned','.heart','.mk','.check','.fused','.dmg','.slash','.txtov','.slice','.lbimg')
out=[]
def scope(sel):
    s=sel.strip()
    return '#sbwLayer '+s
pos=0
for m in re.finditer(r'(@keyframes[^{]+\{(?:[^{}]*\{[^{}]*\})*[^{}]*\})|(@media[^{]+\{((?:[^{}]*\{[^{}]*\})*)[^{}]*\})|(@property[^{]+\{[^}]*\})|([^{}@]+)\{([^{}]*)\}',css):
    if m.group(1):out.append(m.group(1));continue
    if m.group(4):out.append(m.group(4));continue
    if m.group(2):
        inner=m.group(3);head=m.group(2)[:m.group(2).index('{')]
        rules=[]
        for r in re.finditer(r'([^{}]+)\{([^{}]*)\}',inner):
            sels=[x for x in r.group(1).split(',') if x.strip() and not x.strip().startswith(SKIP)]
            if sels:rules.append(','.join(scope(x) for x in sels)+'{'+r.group(2)+'}')
        if rules:out.append(head+'{'+''.join(rules)+'}')
        continue
    sels=[x for x in m.group(5).split(',') if x.strip() and not x.strip().startswith(SKIP)]
    if sels:out.append(','.join(scope(x) for x in sels)+'{'+m.group(6)+'}')
head='/* GENERATED by website-src/make_game_css.py from website/app.css – do not edit by hand. */\n'
open(os.path.join(root,'website-design','website-screens.css'),'w',encoding='utf-8').write(head+'\n'.join(out)+'\n')
print(len(out),'rules;',len(names),'keyframes prefixed')
